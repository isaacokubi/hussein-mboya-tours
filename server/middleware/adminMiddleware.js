import User from "../models/User.js";



/*
|--------------------------------------------------------------------------
| ADMIN MIDDLEWARE
|--------------------------------------------------------------------------
*/


const adminMiddleware = async(
    req,
    res,
    next
)=>{


try{


    /*
    |--------------------------------------------------------------------------
    | CHECK USER
    |--------------------------------------------------------------------------
    */


    const user =

    await User.findById(

        req.user._id

    );





    if(!user){


        return res.status(401).json({

            success:false,

            message:

            "User not found"

        });


    }








    /*
    |--------------------------------------------------------------------------
    | CHECK ADMIN ROLE
    |--------------------------------------------------------------------------
    */


    if(

        user.role !== "admin"

    ){


        return res.status(403).json({

            success:false,

            message:

            "Admin access required"

        });


    }








    /*
    |--------------------------------------------------------------------------
    | CONTINUE
    |--------------------------------------------------------------------------
    */


    next();



}

catch(error){


    next(error);


}


};








/*
|--------------------------------------------------------------------------
| EXPORTS
|--------------------------------------------------------------------------
*/


export {

    adminMiddleware

};



export default adminMiddleware;
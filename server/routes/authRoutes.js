import express from "express";

import {
    login,
    register,
    getMe
} from "../controllers/authController.js";

import protect from "../middleware/authMiddleware.js";



const router = express.Router();





/*
|--------------------------------------------------------------------------
| AUTH ROUTES
|--------------------------------------------------------------------------
|
| Handles:
| - User registration
| - User login
| - Current authenticated user
|
|--------------------------------------------------------------------------
*/





/*
|--------------------------------------------------------------------------
| REGISTER USER
|--------------------------------------------------------------------------
|
| POST /api/auth/register
|
|--------------------------------------------------------------------------
*/

router.post(
    "/register",
    register
);







/*
|--------------------------------------------------------------------------
| LOGIN USER
|--------------------------------------------------------------------------
|
| POST /api/auth/login
|
|--------------------------------------------------------------------------
*/

router.post(
    "/login",
    login
);







/*
|--------------------------------------------------------------------------
| GET CURRENT USER
|--------------------------------------------------------------------------
|
| GET /api/auth/me
|
| Protected route
|
| Requires:
| Authorization: Bearer TOKEN
|
|--------------------------------------------------------------------------
*/

router.get(
    "/me",
    protect,
    getMe
);







export default router;
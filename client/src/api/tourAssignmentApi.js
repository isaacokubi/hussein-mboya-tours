/*
|--------------------------------------------------------------------------
| TOUR ASSIGNMENT
|--------------------------------------------------------------------------
*/

// ============================================================
// ASSIGN TOUR
// ============================================================

export const assignTour = async (
  tourId,
  assignmentData
) => {
  const { data } = await api.put(
    `/tours/${tourId}/assign`,
    assignmentData
  );

  return data;
};
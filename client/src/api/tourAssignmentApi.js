import api from "./axios";

/*
|--------------------------------------------------------------------------
| TOURS
|--------------------------------------------------------------------------
*/

// ============================================================
// GET TOURS
// ============================================================

export const getTours = async (params = {}) => {
  const { data } = await api.get(
    "/tours",
    {
      params,
    }
  );

  return data;
};


import {
    useQuery
} from "@tanstack/react-query";


import {
    fetchAgentDashboard
} from "../api/agentApi";





/*
|--------------------------------------------------------------------------
| AGENT DASHBOARD HOOK
|--------------------------------------------------------------------------
|
| Fetches dashboard statistics for logged-in agents.
|
| Data source:
|
| React Component
|        |
|        ↓
| useAgentDashboard()
|        |
|        ↓
| fetchAgentDashboard()
|        |
|        ↓
| GET /api/agent/dashboard
|
|--------------------------------------------------------------------------
*/


export const useAgentDashboard = () => {


    const query = useQuery({


        /*
        |--------------------------------------------------------------------------
        | CACHE KEY
        |--------------------------------------------------------------------------
        */

        queryKey:[

            "agent-dashboard"

        ],




        /*
        |--------------------------------------------------------------------------
        | API FUNCTION
        |--------------------------------------------------------------------------
        */

        queryFn:

        fetchAgentDashboard,





        /*
        |--------------------------------------------------------------------------
        | PRODUCTION SETTINGS
        |--------------------------------------------------------------------------
        */


        staleTime:

        1000 * 60 * 5,



        retry:

        2



    });





    return {


        /*
        |--------------------------------------------------------------------------
        | ORIGINAL QUERY DATA
        |--------------------------------------------------------------------------
        */


        ...query,





        /*
        |--------------------------------------------------------------------------
        | SAFE DEFAULT VALUES
        |--------------------------------------------------------------------------
        |
        | Prevents UI crashes when API is loading.
        |
        |--------------------------------------------------------------------------
        */


        dashboard:

        query.data || {},



        stats:

        query.data?.stats || {},



        bookings:

        query.data?.bookings || []



    };


};